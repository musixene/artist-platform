import { test, expect } from '@playwright/test';
test('listener registers, plays/selects/seeks, changes queue modes, logs out and signs back in', async ({ page }) => {
  const failures = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Come on in.' })).toBeVisible();
  await page.getByRole('button', { name: 'New here? Create a listener account' }).click();
  await page.getByLabel('Username', { exact: true }).fill('browser-listener');
  await page.getByLabel('Password', { exact: true }).fill('a synthetic browser passphrase');
  await page.getByRole('button', { name: 'Create listener account', exact: true }).click();
  await expect(page.locator('.track')).toHaveCount(3);
  await page.locator('.track').first().click();
  await expect.poll(() => page.locator('audio').evaluate(audio => !audio.paused && audio.currentTime > 0)).toBe(true);
  await expect(page.locator('#now-title')).toHaveText('Morning signal');
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await expect.poll(() => page.locator('audio').evaluate(audio => audio.paused)).toBe(true);
  await page.locator('#seek').evaluate(input => { input.value = '8'; input.dispatchEvent(new Event('input', { bubbles: true })); });
  await expect.poll(() => page.locator('audio').evaluate(audio => Math.round(audio.currentTime))).toBe(8);
  await page.getByRole('button', { name: 'Next track', exact: true }).click();
  await expect(page.locator('#now-title')).toHaveText('Small hours');
  await page.locator('.track').last().click();
  await expect(page.locator('#now-title')).toHaveText('Open horizon');
  await page.getByRole('button', { name: 'Repeat off', exact: true }).click();
  // Real media ending crosses the queue boundary, rather than mocking the controller.
  await page.locator('audio').evaluate(audio => { audio.currentTime = audio.duration - 0.15; });
  await expect(page.locator('#now-title')).toHaveText('Morning signal');
  await page.getByRole('button', { name: 'Shuffle', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Shuffle', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Next track', exact: true }).click();
  await expect(page.locator('#now-title')).not.toHaveText('Morning signal');
  await expect.poll(() => page.evaluate(() => navigator.mediaSession?.metadata?.title)).not.toBeNull();
  await page.reload();
  await expect(page.locator('.track')).toHaveCount(3);
  const privateCached = await page.evaluate(async () => (await Promise.all((await caches.keys()).map(async key => (await (await caches.open(key)).keys()).map(r => new URL(r.url).pathname)))).flat().filter(path => path.startsWith('/api/')));
  expect(privateCached).toEqual([]);
  await expect.poll(() => page.evaluate(async () => !!(await navigator.serviceWorker.ready).active)).toBe(true);
  await expect(page.getByRole('link', { name: 'Powered by an Open Source Concept from Musixene' })).toHaveAttribute('href', 'https://musixene.com');
  await page.screenshot({ path: '/tmp/musixene-library.png', fullPage: true });
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.locator('#auth')).toBeVisible();
  await expect(page.locator('#player')).toBeHidden();
  await page.getByLabel('Username', { exact: true }).fill('browser-listener');
  await page.getByLabel('Password', { exact: true }).fill('a synthetic browser passphrase');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.track')).toHaveCount(3);
  expect(failures).toEqual([]);
});
